/**
 * dart_hooks.cpp - inline hooks for the launcher's Dart AOT code.
 *
 * A Dart AOT function is an AAPCS64 function whose return value is a *tagged
 * pointer* to a Dart object, not a C++ value: `false` is a RawBool object,
 * `null` is a RawNull object and a Widget is a snapshot object. Returning 0
 * therefore returns Smi 0 (the int 0), not false, null or an empty Widget.
 *
 * The ABI also keeps live values in registers C++ does not describe:
 *
 *     x15 Dart stack pointer, x21 dispatch table, x22 NullObject, x24 code,
 *     x26 THR, x27 PP (pool), x28 HEAP_BITS (write barrier)
 *
 * x21, x22, x24, x26, x27 and x28 are callee-saved under AAPCS64 and CMake
 * compiles this file with -ffixed-x21/x22/x24/x26/x27/x28, so the C compiler
 * never allocates them: a replacement can read the pool through PP and return
 * the canonical null/false objects from x22.
 *
 * x15 is the exception. Dart uses it as its stack pointer, and every AOT
 * function ends with `mov x15, x29; ldp x29, x30, [x15], #0x10; ret`, i.e. a
 * callee has to hand x15 back unchanged - and callers depend on it:
 * _showAllAppsArrowIndicator stores a stack argument with `str x16, [x15]` at
 * 0x1176cac, immediately after `bl 0x1b55d50`. AAPCS64, however, classifies
 * x15 as a scratch register, so a C++ replacement and every libc call it makes
 * (mincore, sysconf, __android_log_*) may destroy it. C cannot express "keep
 * this register live across a call", so each hook enters through the asm shim
 * generated by MIUIHOME_HOOK: it saves x15, x0-x8 and q0-q7, calls the C++
 * decision function, restores all of them, and then either returns the
 * decision's value or branches to Dobby's trampoline.
 *
 * In this launcher build the constants do *not* live in the precompiled image:
 * AOT serialises them into the isolate's global object pool, which is created
 * on the heap at startup. PP (x27) points at that one pool and every compiled
 * function in the isolate uses it, so a pool byte offset taken from any
 * disassembly is valid from every hook. The pool stores tagged pointers, and
 * the canonical `true`/`false` are not pool entries at all: the compiler
 * materialises them as NullObject+0x20 / NullObject+0x30 (x22).
 *
 * Pool objects are immutable and pinned by the snapshot, and the canonical
 * bools are VM constants, so caching/reusing them is allocation-free and safe.
 */

